
// Intent types per user message → structured command mapping.
export type CommandType =
  | "CREATE_INCOME"
  | "CREATE_EXPENSE"
  | "CREATE_TRANSFER"
  | "CREATE_OPENING_BALANCE"
  | "BALANCE_ADJUSTMENT"
  | "VOID_TRANSACTION"
  | "EDIT_TRANSACTION";

/** Validated intent after successful parsing & validation. */
export interface FinancialIntent {
  idempotencyKey: string; // generated by application layer
  userId: string;         // derived from auth context
  commandType: CommandType;
  payload:
    | CreateIncomePayload
    | CreateExpensePayload
    | CreateTransferPayload
    | CreateOpeningBalancePayload
    | BalanceAdjustmentPayload
    | VoidTransactionPayload
    | EditTransactionPayload;
}

/** Create Income intent: money masuk ke asset. */
export interface CreateIncomePayload {
  amount: bigint;
  destinationAssetId: string;     // resolved from name to DB UUID
  description?: string | null;
  category?: string | null;       // will be normalized by domain/category.ts
  transactionDate?: string;
}

/** Create Expense intent: uang keluar dari asset. */
export interface CreateExpensePayload {
  amount: bigint;
  sourceAssetId: string;          // resolved from name to DB UUID
  description?: string | null;
  category?: string | null;       // nullable if ambiguous/not provided
  transactionDate?: string;
}

/** Create Transfer intent: pindahkan antar asset. */
export interface CreateTransferPayload {
  amount: bigint;
  sourceAssetId: string;          // resolved from name to DB UUID
  destinationAssetId: string;     // resolved from name to DB UUID
  description?: string | null;
  transactionDate?: string;
}

/** Opening Balance: set initial value of an asset (no cashflow). */
export interface CreateOpeningBalancePayload {
  amount: bigint;
  assetId: string;                // resolved from name to DB UUID
}

/** Balance Adjustment: reconciliation adjustment (set actual value). */
export interface BalanceAdjustmentPayload {
  amount: bigint;                 // actual value
  assetId: string;                // resolved from name to DB UUID
  description?: string | null;    // reason for reconciliation traceability
}

/** Void Transaction: void existing transaction. */
export interface VoidTransactionPayload {
  transactionId: string;          // explicit transaction ID or search by date+amount+type
  reason?: string | null;
}

/** Edit Transaction: direct edit or replacement edit (handled by command layer). */
export interface EditTransactionPayload {
  transactionId: string;          // explicit transaction ID
  patch: {
    description?: string | null;
    category?: string | null;
    transactionDate?: string;
    amount?: bigint;              // triggers replacement edit flow
    sourceAssetId?: string;       // triggers replacement edit flow
    destinationAssetId?: string;  // triggers replacement edit flow
  };
}

/** Parser ambiguity warnings returned alongside parsed intent. */
export interface ParseResult {
  success: boolean;
  intent: FinancialIntent | null;
  ambiguities: ParserAmbiguity[];
  missingFields: MissingField[];
}

export interface ParserAmbiguity {
  type: "AMBIGUOUS_CATEGORY" | "AMBIGUOUS_ASSET" | "INVALID_AMOUNT_FORMAT";
  message: string;               // human-readable warning shown to user
  suggestion?: string;           // optional recovery hint
}

export interface MissingField {
  fieldName: string;             // e.g., "amount", "source_asset", "destination_asset"
  expectedFormat: string;        // e.g., "Rp50.000 atau 50000"
  detectedValue?: string;        // what was captured in the message
}

/** Interface for all parsers. Application layer uses this contract. */
export interface TransactionParser {
  parse(userId: string, rawMessage: string): Promise<ParseResult>;
  isSupported(message: string): boolean;   // fast check before parsing
}

/** Parser implementation strategies. */
export type ParserStrategy = "mock" | "simple-rules" | "ai";
